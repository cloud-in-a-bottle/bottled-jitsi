"""Tiny HTTP service that backs Jitsi local-recording upload + listing.

Runs inside the openhost-jitsi container alongside the four jitsi
services (web/prosody/jicofo/jvb), listens on 127.0.0.1:5060, and is
proxied to by nginx under /api/recordings/* and /<admin_token>/*.

Threat model
------------

Two classes of endpoint:

* ``/api/recordings/{init,<id>/chunk,<id>/finalize}`` — anonymous;
  anyone in a meeting can upload. The room name is a string the
  client provides and we store but don't trust.
* ``/_recordings/<admin_token>/*`` — admin endpoints, where
  ``<admin_token>`` is a 24-byte URL-safe random string (32
  base64url characters) generated on first boot and printed to the
  container logs. Possessing the token grants list / download /
  delete on every recording, indefinitely. There is no per-recording
  ACL — recordings live or die by whoever holds the admin URL.
  Treat the admin URL like a password.

  The ``/_recordings/`` prefix exists so the URL doesn't collide
  with Jitsi room names (Jitsi's room URLs are bare path segments
  like ``/randomwordname``; the underscore prefix can never be
  generated by the Jitsi UI's room-name generator).

Storage
-------

Files live under the directory passed via ``--rec-dir`` (the
``recordings-init.sh`` cont-init points it at
``$OPENHOST_APP_DATA_DIR/recordings``):

    <id>.webm   - the finished recording
    <id>.json   - {id, room, started_by, started_at, finished_at,
                   size_bytes, finalized}

While a recording is uploading, the file lives at ``<id>.webm.tmp``
and the JSON has ``finalized: false``. ``finalize`` swaps it to
``<id>.webm``. A startup sweep deletes any orphaned ``*.tmp`` files
and any JSON whose recording file is missing.

A total-size quota (``--max-bytes``, default 5 GiB) is enforced by
deleting the oldest finalized recordings AFTER a successful chunk
write. Pre-write eviction would let an attacker trigger eviction by
claiming a large Content-Length and disconnecting; we instead
fail-fast a chunk that couldn't possibly fit even with maximum
eviction, and only actually evict once we've received bytes.
"""

from __future__ import annotations

import argparse
import html
import json
import logging
import os
import re
import secrets
import shutil
import sys
import threading
from datetime import datetime, timezone
from http import HTTPStatus
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Any
from urllib.parse import parse_qs, urlparse

logger = logging.getLogger("openhost-jitsi-recordings")


# Default cap; override with --max-bytes (set via the run-script
# render in recordings-init.sh; no env var path).
DEFAULT_MAX_BYTES = 5 * 1024 * 1024 * 1024  # 5 GiB
DEFAULT_CHUNK_SIZE = 5 * 1024 * 1024  # 5 MiB

# Hard upper bound on a single chunk request. The JS shim sends 5 MiB
# chunks; we cap a bit above that to leave room for a future bump
# without rolling the wire format. Without this cap a malicious or
# buggy client can claim Content-Length: <huge> in one request and
# trigger preemptive eviction of every existing finalized recording
# before sending a single byte.
MAX_CHUNK_BYTES = 16 * 1024 * 1024  # 16 MiB

# Recording IDs are URL-safe random hex; we generate them ourselves and
# never trust client input.
ID_RE = re.compile(r"^[a-f0-9]{16}$")
ROOM_RE = re.compile(r"^[A-Za-z0-9._\- ]{1,128}$")

# Lock guarding state-file mutations and quota eviction.  All file IO
# inside this lock is local-disk-only and bounded; we don't hold it
# across the multi-megabyte chunk reads themselves.
_state_lock = threading.RLock()

# Per-recording locks serialize chunk writes for a single recording
# so concurrent POSTs for the same rec_id can't interleave bytes in
# the .webm.tmp file. The ``_state_lock`` guards mutations of this
# dict itself; the lock objects within it are then taken outside the
# global state lock so multiple recordings can stream concurrently.
_chunk_locks: dict[str, threading.Lock] = {}


def _chunk_lock_for(rec_id: str) -> threading.Lock:
    with _state_lock:
        lock = _chunk_locks.get(rec_id)
        if lock is None:
            lock = threading.Lock()
            _chunk_locks[rec_id] = lock
        return lock


def _drop_chunk_lock(rec_id: str) -> None:
    with _state_lock:
        _chunk_locks.pop(rec_id, None)


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _meta_path(rec_dir: Path, rec_id: str) -> Path:
    return rec_dir / f"{rec_id}.json"


def _final_path(rec_dir: Path, rec_id: str) -> Path:
    return rec_dir / f"{rec_id}.webm"


def _tmp_path(rec_dir: Path, rec_id: str) -> Path:
    return rec_dir / f"{rec_id}.webm.tmp"


def _read_meta(rec_dir: Path, rec_id: str) -> dict[str, Any] | None:
    try:
        return json.loads(_meta_path(rec_dir, rec_id).read_text())
    except FileNotFoundError:
        return None
    except json.JSONDecodeError:
        logger.warning("Corrupt metadata for %s; ignoring", rec_id)
        return None
    except OSError as e:
        # Permissions / IO error reading the file. Log and treat as
        # "no such recording" so callers don't propagate raw
        # filesystem errors back to clients.
        logger.warning("Could not read metadata for %s: %s", rec_id, e)
        return None


def _write_meta(rec_dir: Path, rec_id: str, meta: dict[str, Any]) -> None:
    path = _meta_path(rec_dir, rec_id)
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(meta, sort_keys=True))
    os.replace(tmp, path)


def _list_meta(rec_dir: Path) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for p in sorted(rec_dir.glob("*.json")):
        rec_id = p.stem
        if not ID_RE.fullmatch(rec_id):
            continue
        meta = _read_meta(rec_dir, rec_id)
        if meta is None:
            continue
        out.append(meta)
    out.sort(key=lambda m: m.get("started_at", ""), reverse=True)
    return out


def _disk_usage(rec_dir: Path) -> int:
    """Total bytes consumed by finalized recordings + in-flight tmp
    uploads. We count tmp files so a flood of unfinalized uploads
    can't bypass the quota.
    """
    total = 0
    for p in rec_dir.iterdir():
        if p.is_file():
            try:
                total += p.stat().st_size
            except OSError as e:
                logger.warning("Could not stat %s for quota accounting: %s", p.name, e)
    return total


def _evict_until_under_cap(rec_dir: Path, headroom_bytes: int, max_bytes: int) -> None:
    """Delete oldest finalized recordings until total + headroom <= cap.

    Tmp uploads-in-progress are NOT evicted (we don't know if more
    bytes are coming) but they ARE counted in the total — a flood of
    unfinalized uploads will refuse to evict any finalized recordings
    once finalized bytes alone are under the cap.
    """
    metas = sorted(_list_meta(rec_dir), key=lambda m: m.get("started_at", ""))
    total = _disk_usage(rec_dir)
    for meta in metas:
        if total + headroom_bytes <= max_bytes:
            return
        if not meta.get("finalized"):
            continue
        rec_id = meta["id"]
        size = int(meta.get("size_bytes", 0))
        # Delete the data file first; if that fails we keep the
        # metadata so the listing still shows the broken recording.
        # If only the metadata delete fails we still subtract from
        # ``total`` — the bytes are gone — and the next startup
        # sweep will reap the orphan json.
        try:
            _final_path(rec_dir, rec_id).unlink(missing_ok=True)
        except OSError as e:
            logger.warning("Eviction of %s data failed: %s", rec_id, e)
            continue
        try:
            _meta_path(rec_dir, rec_id).unlink(missing_ok=True)
        except OSError as e:
            logger.warning("Eviction of %s metadata failed (file already deleted): %s", rec_id, e)
        total -= size
        logger.info("Evicted %s (%d bytes) to make room", rec_id, size)


def _sweep_orphans(rec_dir: Path) -> None:
    """At startup: drop *.tmp / *.json.tmp files (interrupted writes),
    metadata for finalized recordings whose .webm is missing, and
    metadata for unfinalized recordings whose .webm.tmp is also gone
    (these can't ever be resumed and would otherwise stay visible
    forever as 'uploading').

    The .tmp sweep runs first, so the json sweep's existence check
    catches the cases where we just deleted the corresponding .tmp.
    """
    for pattern in ("*.webm.tmp", "*.json.tmp"):
        for p in rec_dir.glob(pattern):
            try:
                p.unlink()
                logger.info("Removed orphan %s", p.name)
            except OSError as e:
                logger.warning("Could not remove orphan %s: %s", p.name, e)
    for p in rec_dir.glob("*.json"):
        rec_id = p.stem
        if not ID_RE.fullmatch(rec_id):
            continue
        meta = _read_meta(rec_dir, rec_id)
        if meta is None:
            continue
        finalized = bool(meta.get("finalized"))
        has_final = _final_path(rec_dir, rec_id).exists()
        has_tmp = _tmp_path(rec_dir, rec_id).exists()
        if finalized and not has_final:
            stale_reason = "missing recording file"
        elif not finalized and not has_tmp:
            stale_reason = "no .webm.tmp; upload was interrupted and can't resume"
        else:
            continue
        try:
            p.unlink()
            logger.info("Removed metadata for %s (%s)", rec_id, stale_reason)
        except OSError as e:
            logger.warning("Could not remove orphan metadata %s: %s", p.name, e)


def _new_rec_id() -> str:
    return secrets.token_hex(8)


def _load_or_create_admin_token(token_path: Path) -> str:
    try:
        if token_path.exists():
            token = token_path.read_text().strip()
            if token:
                return token
        token = secrets.token_urlsafe(24)
        token_path.parent.mkdir(parents=True, exist_ok=True)
        token_path.write_text(token)
    except OSError as e:
        logger.exception("FATAL: cannot read or create admin token file %s", token_path)
        raise RuntimeError(f"admin token IO failed: {e}") from e
    try:
        token_path.chmod(0o600)
    except OSError as e:
        # Token file is potentially world-readable; warn loudly so an
        # operator noticing odd permissions has an audit trail.
        logger.warning("Could not chmod admin token file %s to 0600: %s", token_path, e)
    return token


