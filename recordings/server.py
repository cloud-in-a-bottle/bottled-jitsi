class _State:
    """Per-server state shared by handler instances via a class attr."""

    def __init__(
        self,
        rec_dir: Path,
        admin_token: str,
        max_bytes: int,
        public_origin_hint: str | None,
    ) -> None:
        self.rec_dir = rec_dir
        self.admin_token = admin_token
        self.max_bytes = max_bytes
        # Origin (scheme+host) used only when the server logs the
        # listing URL at startup, so the operator can paste it into
        # a browser. Inside the listing page itself, all URLs are
        # relative.
        self.public_origin_hint = public_origin_hint or ""


class _Handler(BaseHTTPRequestHandler):
    state: _State  # set before serving

    server_version = "openhost-jitsi-recordings/1"

    # Silence the default per-request stderr logging; we log
    # explicitly for the requests we care about.
    def log_message(self, format: str, *args: Any) -> None:  # noqa: A002, D401
        return

    # -- helpers ------------------------------------------------------------

    def _json(self, status: int, payload: dict[str, Any]) -> None:
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _error(self, status: int, message: str) -> None:
        self._json(status, {"error": message})

    def _read_json_body(self, max_bytes: int = 64 * 1024) -> dict[str, Any] | None:
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            return None
        if length <= 0 or length > max_bytes:
            return None
        try:
            data = self.rfile.read(length)
        except OSError:
            return None
        try:
            payload = json.loads(data.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError):
            return None
        return payload if isinstance(payload, dict) else None

    # -- routing ------------------------------------------------------------

    def do_GET(self) -> None:  # noqa: N802 (BaseHTTPRequestHandler API)
        url = urlparse(self.path)
        path = url.path

        if path == "/api/recordings/health":
            return self._json(200, {"ok": True})

        # Admin endpoints under /_recordings/<token>/...
        admin_match = re.match(r"^/_recordings/([^/]+)/?(.*)$", path)
        if admin_match and secrets.compare_digest(admin_match.group(1), self.state.admin_token):
            tail = admin_match.group(2)
            return self._handle_admin_get(tail, parse_qs(url.query))

        return self._error(HTTPStatus.NOT_FOUND, "not found")

    def do_POST(self) -> None:  # noqa: N802
        url = urlparse(self.path)
        path = url.path

        if path == "/api/recordings/init":
            return self._handle_init()

        chunk_match = re.match(r"^/api/recordings/([a-f0-9]{16})/chunk$", path)
        if chunk_match:
            return self._handle_chunk(chunk_match.group(1))

        finalize_match = re.match(r"^/api/recordings/([a-f0-9]{16})/finalize$", path)
        if finalize_match:
            return self._handle_finalize(finalize_match.group(1))

        return self._error(HTTPStatus.NOT_FOUND, "not found")

    def do_DELETE(self) -> None:  # noqa: N802
        url = urlparse(self.path)
        path = url.path
        admin_match = re.match(r"^/_recordings/([^/]+)/recording/([a-f0-9]{16})$", path)
        if admin_match and secrets.compare_digest(admin_match.group(1), self.state.admin_token):
            rec_id = admin_match.group(2)
            return self._handle_admin_delete(rec_id)
        return self._error(HTTPStatus.NOT_FOUND, "not found")

    # -- handlers: anonymous upload path -----------------------------------

    def _handle_init(self) -> None:
        body = self._read_json_body() or {}
        room = str(body.get("room", "")).strip()
        started_by = str(body.get("started_by", "")).strip()[:64] or "anonymous"
        if not ROOM_RE.fullmatch(room):
            return self._error(HTTPStatus.BAD_REQUEST, "invalid room")

        rec_id = _new_rec_id()
        meta = {
            "id": rec_id,
            "room": room,
            "started_by": started_by,
            "started_at": _now_iso(),
            "finished_at": None,
            "size_bytes": 0,
            "finalized": False,
        }
        with _state_lock:
            try:
                _tmp_path(self.state.rec_dir, rec_id).touch()
                _write_meta(self.state.rec_dir, rec_id, meta)
            except OSError as e:
                logger.exception("init failed for %s", rec_id)
                return self._error(HTTPStatus.INTERNAL_SERVER_ERROR, f"could not initialize recording: {e}")
        logger.info("init recording %s in room %r by %r", rec_id, room, started_by)
        return self._json(200, {"id": rec_id, "chunk_size": DEFAULT_CHUNK_SIZE})

    def _handle_chunk(self, rec_id: str) -> None:
        if not ID_RE.fullmatch(rec_id):
            return self._error(HTTPStatus.BAD_REQUEST, "invalid id")
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            return self._error(HTTPStatus.BAD_REQUEST, "invalid Content-Length")
        if length <= 0:
            return self._error(HTTPStatus.BAD_REQUEST, "empty chunk")
        if length > MAX_CHUNK_BYTES:
            return self._error(HTTPStatus.REQUEST_ENTITY_TOO_LARGE, f"chunk too large (max {MAX_CHUNK_BYTES})")

        with _state_lock:
            meta = _read_meta(self.state.rec_dir, rec_id)
            if meta is None:
                return self._error(HTTPStatus.NOT_FOUND, "no such recording")
            if meta.get("finalized"):
                return self._error(HTTPStatus.CONFLICT, "already finalized")
            tmp = _tmp_path(self.state.rec_dir, rec_id)
            if not tmp.exists():
                return self._error(HTTPStatus.GONE, "recording gone")
            # Quick fail-fast capacity check: reject if even our most
            # aggressive eviction couldn't fit the chunk. We don't
            # ACT on the eviction yet — that happens only after we've
            # actually received bytes — but if there's no possible way
            # for the chunk to land, the client deserves an early 507.
            #
            # NOTE: this is an over-approximation. ``_disk_usage`` counts
            # every file in the recordings dir (json, tmp, webm),
            # while ``size_bytes`` only tracks .webm size; a finalized
            # recording's metadata file (~150 bytes) effectively
            # raises the floor by that much. The miscounting only
            # over-rejects, never under-rejects, so it's a soft
            # tightening of the cap rather than a leak.
            current_usage = _disk_usage(self.state.rec_dir)
            evictable = sum(
                int(m.get("size_bytes", 0))
                for m in _list_meta(self.state.rec_dir)
                if m.get("finalized")
            )
            if (current_usage - evictable) + length > self.state.max_bytes:
                return self._error(
                    HTTPStatus.INSUFFICIENT_STORAGE,
                    "disk quota exceeded; even evicting all finalized recordings wouldn't fit",
                )

        # Take the per-recording lock so two POSTs for the same
        # rec_id don't interleave bytes in the tmp file. We hold it
        # across the streaming + metadata-update pair; concurrent
        # chunks for DIFFERENT recordings still proceed in parallel.
        rec_lock = _chunk_lock_for(rec_id)
        with rec_lock:
            return self._stream_chunk_locked(rec_id, length, tmp)

    def _stream_chunk_locked(self, rec_id: str, length: int, tmp: Path) -> None:
        # Stream the body to disk in fixed-size reads outside the global lock.
        # Only AFTER we have actual bytes do we trigger eviction —
        # otherwise an attacker could claim a large Content-Length,
        # disconnect, and force eviction of every finalized recording
        # while contributing zero bytes themselves.
        #
        # If the write fails partway, truncate back to the pre-chunk
        # size so that a client retry doesn't append duplicate bytes
        # on top of a partial write (would corrupt the WebM).
        try:
            pre_chunk_size = tmp.stat().st_size
        except OSError:
            # Concurrent admin DELETE removed tmp between the lock
            # release and here; the upload is dead.
            return self._error(HTTPStatus.GONE, "recording was deleted before chunk could be written")
        try:
            written = self._stream_to_file(tmp, length)
        except OSError as e:
            logger.exception("write failed for %s; rolling back tmp to %d bytes", rec_id, pre_chunk_size)
            # Open in r+b (not ab) so a concurrent admin DELETE that
            # removed the tmp file produces FileNotFoundError instead
            # of recreating an empty file.
            try:
                with tmp.open("r+b") as fh:
                    fh.truncate(pre_chunk_size)
            except FileNotFoundError:
                logger.info("rollback skipped: tmp for %s was deleted concurrently", rec_id)
            except OSError as e2:
                logger.warning("rollback truncate failed for %s: %s; tmp may be corrupted", rec_id, e2)
            return self._error(HTTPStatus.INTERNAL_SERVER_ERROR, f"write failed: {e}")

        with _state_lock:
            meta = _read_meta(self.state.rec_dir, rec_id)
            if meta is None:
                # An admin DELETE finished while we were streaming.
                # Don't recreate metadata for a recording that was
                # explicitly removed; just drop the bytes we wrote.
                try:
                    _tmp_path(self.state.rec_dir, rec_id).unlink(missing_ok=True)
                except OSError:
                    pass
                return self._error(HTTPStatus.NOT_FOUND, "recording was deleted mid-upload")
            try:
                meta["size_bytes"] = int(meta.get("size_bytes", 0)) + written
                _write_meta(self.state.rec_dir, rec_id, meta)
            except OSError as e:
                logger.exception("metadata write failed after chunk for %s", rec_id)
                return self._error(HTTPStatus.INTERNAL_SERVER_ERROR, f"metadata write failed: {e}")
            # Now that we've actually written bytes, evict if needed
            # to bring total usage back under the cap.
            _evict_until_under_cap(self.state.rec_dir, 0, self.state.max_bytes)
        return self._json(200, {"ok": True, "received": written, "total": meta["size_bytes"]})

    def _handle_finalize(self, rec_id: str) -> None:
        if not ID_RE.fullmatch(rec_id):
            return self._error(HTTPStatus.BAD_REQUEST, "invalid id")
        with _state_lock:
            meta = _read_meta(self.state.rec_dir, rec_id)
            if meta is None:
                return self._error(HTTPStatus.NOT_FOUND, "no such recording")
            tmp = _tmp_path(self.state.rec_dir, rec_id)
            final = _final_path(self.state.rec_dir, rec_id)
            if meta.get("finalized"):
                if final.exists():
                    return self._json(200, {"ok": True, "already_finalized": True})
                return self._error(HTTPStatus.GONE, "recording deleted after finalize")
            # Repair-on-retry: a previous finalize may have done the
            # rename, then crashed before persisting `finalized=True`.
            # Detect that and proceed to repair the metadata only.
            if not tmp.exists() and final.exists():
                logger.info("finalize-retry: tmp gone, final present for %s; repairing meta", rec_id)
            elif not tmp.exists():
                return self._error(HTTPStatus.GONE, "recording gone")
            else:
                try:
                    os.replace(tmp, final)
                except OSError as e:
                    logger.exception("rename failed for %s", rec_id)
                    return self._error(HTTPStatus.INTERNAL_SERVER_ERROR, f"rename failed: {e}")
            # Bytes are committed (either we just renamed or a prior
            # finalize did). Stamp meta. If the metadata write fails,
            # the next retry hits the repair branch above and tries
            # again.
            try:
                size = final.stat().st_size
            except OSError as e:
                logger.warning("stat failed after rename for %s: %s; using tracked size", rec_id, e)
                size = int(meta.get("size_bytes", 0))
            meta["finished_at"] = _now_iso()
            meta["size_bytes"] = size
            meta["finalized"] = True
            try:
                _write_meta(self.state.rec_dir, rec_id, meta)
            except OSError as e:
                logger.exception("metadata write failed in finalize for %s", rec_id)
                return self._error(HTTPStatus.INTERNAL_SERVER_ERROR, f"metadata write failed: {e}")
        logger.info("finalized recording %s (%d bytes)", rec_id, meta["size_bytes"])
        # No more chunks will arrive for this recording; drop its lock.
        _drop_chunk_lock(rec_id)
        return self._json(200, {"ok": True})

    def _stream_to_file(self, path: Path, length: int) -> int:
        """Copy ``length`` bytes from rfile to the end of ``path``."""
        copied = 0
        # Open in append mode; multiple chunks accumulate.
        with path.open("ab") as out:
            remaining = length
            while remaining > 0:
                buf = self.rfile.read(min(64 * 1024, remaining))
                if not buf:
                    raise OSError("client disconnected mid-chunk")
                out.write(buf)
                copied += len(buf)
                remaining -= len(buf)
        return copied

    # -- handlers: admin path ----------------------------------------------

    def _handle_admin_get(self, tail: str, query: dict[str, list[str]]) -> None:
        # /<token>/        → HTML listing (do_GET's regex consumes
        # the trailing slash before the tail capture, so tail is "")
        # /<token>/recording/<id> → file download
        if tail == "":
            return self._render_listing()
        m = re.match(r"^recording/([a-f0-9]{16})$", tail)
        if m:
            return self._serve_recording(m.group(1))
        return self._error(HTTPStatus.NOT_FOUND, "not found")

    def _handle_admin_delete(self, rec_id: str) -> None:
        errors: list[str] = []
        # Drop any per-recording chunk lock so a future re-init with
        # the same id (extremely unlikely; ids are 64-bit random) or
        # a stuck thread doesn't keep a dead reference around.
        _drop_chunk_lock(rec_id)
        with _state_lock:
            meta = _read_meta(self.state.rec_dir, rec_id)
            if meta is None:
                return self._error(HTTPStatus.NOT_FOUND, "no such recording")
            for p in (
                _final_path(self.state.rec_dir, rec_id),
                _tmp_path(self.state.rec_dir, rec_id),
                _meta_path(self.state.rec_dir, rec_id),
            ):
                try:
                    p.unlink(missing_ok=True)
                except OSError as e:
                    logger.warning("delete %s: %s", p, e)
                    errors.append(f"{p.name}: {e}")
        if errors:
            # Some files couldn't be removed; surface the failure so
            # the admin UI doesn't show a misleading green tick.
            return self._error(HTTPStatus.INTERNAL_SERVER_ERROR, "; ".join(errors))
        return self._json(200, {"ok": True})

    def _serve_recording(self, rec_id: str) -> None:
        meta = _read_meta(self.state.rec_dir, rec_id)
        if meta is None or not meta.get("finalized"):
            return self._error(HTTPStatus.NOT_FOUND, "not found")
        path = _final_path(self.state.rec_dir, rec_id)
        # Open before reading the size so the size we send in the
        # Content-Length header matches the bytes we'll actually
        # stream. A concurrent DELETE between stat and open would
        # otherwise either truncate the response or surface as an
        # unhandled OSError after headers are already sent.
        try:
            fh = path.open("rb")
        except FileNotFoundError:
            return self._error(HTTPStatus.NOT_FOUND, "not found")
        except OSError as e:
            logger.exception("could not open %s for serving", rec_id)
            return self._error(HTTPStatus.INTERNAL_SERVER_ERROR, f"open failed: {e}")

        try:
            size = os.fstat(fh.fileno()).st_size
            room = meta.get("room", "recording")
            safe_room = re.sub(r"[^A-Za-z0-9._-]", "_", room)
            ts = (meta.get("started_at", "") or "").replace(":", "-")
            download_name = f"{safe_room}_{ts}.webm"

            self.send_response(200)
            self.send_header("Content-Type", "video/webm")
            self.send_header("Content-Length", str(size))
            self.send_header("Content-Disposition", f'attachment; filename="{download_name}"')
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            try:
                shutil.copyfileobj(fh, self.wfile, length=64 * 1024)
            except (BrokenPipeError, ConnectionResetError):
                # Client gave up mid-download; nothing actionable.
                pass
        finally:
            fh.close()

    def _render_listing(self) -> None:
        recordings = _list_meta(self.state.rec_dir)
        total_bytes = sum(int(m.get("size_bytes", 0)) for m in recordings if m.get("finalized"))
        rows = []
        for m in recordings:
            if not m.get("finalized"):
                state = "uploading"
                action = ""
            else:
                state = "ready"
                action = (
                    f'<a href="recording/{m["id"]}">download</a> '
                    f'<a href="#" onclick="del(\'{m["id"]}\');return false">delete</a>'
                )
            size_mb = f'{m.get("size_bytes", 0) / 1_000_000:.1f}'
            rows.append(
                "<tr>"
                f'<td>{html.escape(m.get("room", ""))}</td>'
                f'<td>{html.escape(m.get("started_at", ""))}</td>'
                f'<td>{html.escape(m.get("started_by", ""))}</td>'
                f'<td style="text-align:right">{size_mb} MB</td>'
                f"<td>{state}</td>"
                f"<td>{action}</td>"
                "</tr>"
            )
        body = LISTING_HTML.format(
            rows="\n".join(rows) or '<tr><td colspan="6" style="text-align:center;color:#888">No recordings yet.</td></tr>',
            total_mb=f"{total_bytes / 1_000_000:.1f}",
            cap_mb=f"{self.state.max_bytes / 1_000_000:.0f}",
            count=len(recordings),
        )
        encoded = body.encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(encoded)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(encoded)


